/// JSON 深合并：dict 递归；数组并集去重；其余 override 优先
fn deep_merge(base: &Value, over: &Value) -> Value {
    match (base, over) {
        (Value::Object(b), Value::Object(o)) => {
            let mut m = b.clone();
            for (k, v) in o {
                let merged = match m.get(k) {
                    Some(existing) => deep_merge(existing, v),
                    None => v.clone(),
                };
                m.insert(k.clone(), merged);
            }
            Value::Object(m)
        }
        (Value::Array(b), Value::Array(o)) => {
            let mut out = b.clone();
            for item in o {
                if !out.contains(item) {
                    out.push(item.clone());
                }
            }
            Value::Array(out)
        }
        (_, o) => o.clone(),
    }
}

/// libs/.emmyrc.json（base）+ src/.emmyrc.json（override）-> 项目根 .emmyrc.json
pub fn merge_emmyrc(bgd_root: &Path, cfg: &BgdConfig, log: &LogFn) -> Result<()> {
    let libs_f = cfg.abs(bgd_root, &cfg.libs_dir).join(".emmyrc.json");
    let src_f = cfg.abs(bgd_root, &cfg.game_dir).join(".emmyrc.json");
    let base: Value = if libs_f.exists() {
        serde_json::from_str(&fs::read_to_string(&libs_f)?).unwrap_or(Value::Null)
    } else {
        Value::Null
    };
    let over: Value = if src_f.exists() {
        serde_json::from_str(&fs::read_to_string(&src_f)?).unwrap_or(Value::Null)
    } else {
        Value::Null
    };
    let merged = deep_merge(&base, &over);
    let out = bgd_root
        .parent()
        .unwrap_or(bgd_root)
        .join(".emmyrc.json");
    fs::write(&out, format!("{}\n", serde_json::to_string_pretty(&merged)?))?;
    log("[ok] merge: .emmyrc.json");
    Ok(())
}

/// libs/.gitignore + src/.gitignore -> 项目根 .gitignore（规则行去重）
pub fn merge_gitignore(bgd_root: &Path, cfg: &BgdConfig, log: &LogFn) -> Result<()> {
    let libs_f = cfg.abs(bgd_root, &cfg.libs_dir).join(".gitignore");
    let src_f = cfg.abs(bgd_root, &cfg.game_dir).join(".gitignore");
    let mut sections: Vec<String> = Vec::new();
    let mut seen: std::collections::HashSet<String> = std::collections::HashSet::new();
    for (title, f) in [("框架规则", libs_f), ("项目规则", src_f)] {
        if !f.exists() {
            continue;
        }
        let mut lines = vec![format!("# ==== {title} ====")];
        for line in fs::read_to_string(&f)?.lines() {
            let key = line.trim();
            let is_rule = !key.is_empty() && !key.starts_with('#');
            if is_rule {
                if seen.contains(key) {
                    continue;
                }
                seen.insert(key.to_string());
            }
            lines.push(line.to_string());
        }
        sections.push(lines.join("\n"));
    }
    let out = bgd_root.parent().unwrap_or(bgd_root).join(".gitignore");
    fs::write(&out, format!("{GITIGNORE_HEADER}\n\n{}\n", sections.join("\n\n")))?;
    log("[ok] merge: .gitignore");
    Ok(())
}

/// src/AGENTS.md -> 项目根 AGENTS.md（与 .gitignore 同策略：构建产物，要改就改 .bgd/src/AGENTS.md）
/// 源不存在则不动根文件；内容一致则跳过写入（避免监听触发无意义刷盘）
pub fn sync_agents_md(bgd_root: &Path, cfg: &BgdConfig, log: &LogFn) -> Result<()> {
    let src_f = cfg.abs(bgd_root, &cfg.game_dir).join("AGENTS.md");
    if !src_f.exists() {
        return Ok(());
    }
    let out = bgd_root.parent().unwrap_or(bgd_root).join("AGENTS.md");
    let content = fs::read(&src_f)?;
    if out.exists() && fs::read(&out)? == content {
        return Ok(());
    }
    fs::write(&out, content)?;
    log("[ok] sync: AGENTS.md <- src/AGENTS.md");
    Ok(())
}

// ---------------------------------------------------------------- 全量构建 / 清理

pub fn build_code_set(code_set: &str, bgd_root: &Path, cfg: &BgdConfig, log: &LogFn) -> Result<usize> {
    let (dir, _) = code_set_dir(code_set, cfg);
    let src_root = cfg.abs(bgd_root, dir);
    if !src_root.is_dir() {
        log(&format!("[info] {code_set} 源目录不存在: {}", src_root.display()));
        return Ok(0);
    }
    let mut count = 0;
    for sub in BUILD_SUBDIRS {
        let subdir = src_root.join(sub);
        if !subdir.is_dir() {
            continue;
        }
        for entry in WalkDir::new(&subdir).into_iter().filter_map(|e| e.ok()) {
            if entry.file_type().is_file() {
                count += build_one_file(bgd_root, cfg, code_set, entry.path(), log)?;
            }
        }
    }
    Ok(count)
}

pub fn build_all(bgd_root: &Path, cfg: &BgdConfig, log: &LogFn) -> Result<()> {
    log("===== 开始全量构建 =====");
    regen_api_aggregations(bgd_root, cfg, log)?;
    let libs_count = build_code_set("libs", bgd_root, cfg, log)?;
    let game_count = build_code_set("game", bgd_root, cfg, log)?;
    render_root_init(bgd_root, cfg, log)?;
    update_entrance("server", bgd_root, cfg, log)?;
    update_entrance("client", bgd_root, cfg, log)?;
    merge_emmyrc(bgd_root, cfg, log)?;
    merge_gitignore(bgd_root, cfg, log)?;
    sync_agents_md(bgd_root, cfg, log)?;
    log(&format!(
        "===== 构建完成！框架文件: {libs_count}，游戏文件: {game_count} ====="
    ));
    Ok(())
}

pub fn clean(bgd_root: &Path, cfg: &BgdConfig, log: &LogFn) -> Result<()> {
    log("===== 清除构建产物 =====");
    for target in [
        &cfg.libs_server_target,
        &cfg.libs_client_target,
        &cfg.game_server_target,
        &cfg.game_client_target,
    ] {
        let abs = cfg.abs(bgd_root, target);
        if abs.is_dir() {
            fs::remove_dir_all(&abs)?;
            log(&format!("  -> 已删除 {}", abs.display()));
        } else {
            log(&format!("  -> 目录不存在，跳过 {}", abs.display()));
        }
    }
    restore_entrance("server", bgd_root, cfg, log)?;
    restore_entrance("client", bgd_root, cfg, log)?;
    clean_res_files(bgd_root, log)?;
    log("===== 清理完成 =====");
    Ok(())
}

/// 清除同步到引擎目录的资源文件（ui/image/、res/effect/ 等下的 bgd_* 目录）
fn clean_res_files(bgd_root: &Path, log: &LogFn) -> Result<()> {
    let project_root = bgd_root.parent().unwrap_or(bgd_root);
    for code_set in ["libs", "game"] {
        let prefix = if code_set == "libs" { "bgd_libs_client" } else { "bgd_game_client" };
        for sub in [
            format!("ui/image/image/{prefix}"),
            format!("res/effect/{prefix}"),
            format!("res/sound/{prefix}"),
            format!("ui/spine/{prefix}"),
            format!("ui/image/sprites/{prefix}"),
        ] {
            let path = project_root.join(&sub);
            if path.is_dir() {
                fs::remove_dir_all(&path)?;
                log(&format!("  -> 已删除资源 {sub}"));
            }
        }
    }
    Ok(())
}

/// 清理 .bgd/log 下的 .log 文件，返回删除数量
pub fn clean_logs(bgd_root: &Path, log: &LogFn) -> Result<usize> {
    let log_dir = bgd_root.join("log");
    let mut deleted = 0;
    if log_dir.is_dir() {
        for entry in fs::read_dir(&log_dir)? {
            let path = entry?.path();
            if path.extension().is_some_and(|e| e == "log") {
                fs::remove_file(&path)?;
                deleted += 1;
            }
        }
    }
    log(&format!("日志清理完成，共删除 {deleted} 个 .log 文件"));
    Ok(deleted)
}

// ---------------------------------------------------------------- 监听

fn identify_code_set(path: &Path, bgd_root: &Path, cfg: &BgdConfig) -> Option<&'static str> {
    for code_set in ["libs", "game"] {
        let (dir, _) = code_set_dir(code_set, cfg);
        let src_root = cfg.abs(bgd_root, dir);
        if path.starts_with(&src_root) {
            return Some(code_set);
        }
    }
    None
}

fn delete_outputs(path: &Path, bgd_root: &Path, cfg: &BgdConfig, log: &LogFn) -> Result<()> {
    let Some(code_set) = identify_code_set(path, bgd_root, cfg) else {
        return Ok(());
    };
    let rel = rel_of(path, code_set, bgd_root, cfg)?;
    if !in_whitelist(&rel) {
        return Ok(());
    }
    let (_, excludes) = code_set_dir(code_set, cfg);
    if is_excluded(&rel, excludes) {
        return Ok(());
    }
    for side in sides_for(&rel) {
        let mut dest = dest_for(&rel, side, code_set, bgd_root, cfg);
        let ext = ext_of(&dest);
        if ["html", "css", "js"].contains(&ext.as_str()) {
            dest = dest.with_extension("lua");
        }
        if dest.exists() {
            fs::remove_file(&dest)?;
            log(&format!("[deleted] {side}: [{code_set}] {rel}"));
        }
    }
    Ok(())
}

/// 监听单文件路由：白名单文件增量构建；根级元文件走专门流程
fn handle_file(path: &Path, deleted: bool, bgd_root: &Path, cfg: &BgdConfig, log: &LogFn) {
    let Some(code_set) = identify_code_set(path, bgd_root, cfg) else {
        return;
    };
    let Ok(rel) = rel_of(path, code_set, bgd_root, cfg) else {
        return;
    };

    // 根级 init.lua：模板重渲染
    if rel == "/init.lua" {
        let _ = render_root_init(bgd_root, cfg, log);
        return;
    }
    // 根级 emmyrc/gitignore 片段：重新合并
    if rel == "/.emmyrc.json" {
        let _ = merge_emmyrc(bgd_root, cfg, log);
        return;
    }
    if rel == "/.gitignore" {
        let _ = merge_gitignore(bgd_root, cfg, log);
        return;
    }
    // src/AGENTS.md：同步到项目根
    if rel == "/AGENTS.md" && code_set == "game" {
        let _ = sync_agents_md(bgd_root, cfg, log);
        return;
    }
    // entrance 文件：重新合并入口
    if rel.starts_with("/entrance/") {
        let _ = update_entrance("server", bgd_root, cfg, log);
        let _ = update_entrance("client", bgd_root, cfg, log);
        return;
    }
    // api 目录变动：重新生成聚合并立即构建
    if rel.contains("/api/") {
        if let Ok(gen_files) = regen_api_aggregations(bgd_root, cfg, log) {
            for gen in gen_files {
                if let Some(gen_set) = identify_code_set(&gen, bgd_root, cfg) {
                    let _ = build_one_file(bgd_root, cfg, gen_set, &gen, log);
                }
            }
        }
    }
    // 普通白名单文件
    if deleted {
        let _ = delete_outputs(path, bgd_root, cfg, log);
    } else {
        let _ = build_one_file(bgd_root, cfg, code_set, path, log);
    }
}

/// 启动监听（notify 事件驱动，带事件去重）。返回 watcher 句柄，由调用方持有；drop 即停止。
///
/// Windows 编辑器保存文件（尤其原子保存）会对一次保存派发多个事件，直接逐事件处理
/// 会产生重复构建/重复日志。这里把同一文件在短时间窗口内的事件聚合为一次：
/// 只要窗口结束时文件仍存在就构建一次，不存在则删除一次。
pub fn start_watch<L>(bgd_root: &Path, cfg: &BgdConfig, log: L) -> Result<RecommendedWatcher>
where
    L: Fn(&str) + Send + Sync + 'static,
{
    use std::collections::HashMap;
    use std::sync::mpsc;
    use std::sync::Arc;
    use std::time::{Duration, Instant};

    const DEBOUNCE_MS: u64 = 300;

    let bgd_root = bgd_root.to_path_buf();
    let cfg = cfg.clone();
    let log = Arc::new(log);

    let (tx, rx) = mpsc::channel::<Event>();
    let mut watcher = notify::recommended_watcher(move |res: Result<Event, notify::Error>| {
        if let Ok(event) = res {
            let _ = tx.send(event);
        }
    })?;

    for code_set in ["libs", "game"] {
        let (dir, _) = code_set_dir(code_set, &cfg);
        let src_root = cfg.abs(&bgd_root, dir);
        if src_root.is_dir() {
            watcher.watch(&src_root, RecursiveMode::Recursive)?;
            (log)(&format!("[watch] 正在监听: {}", src_root.display()));
        }
    }
    (log)("[watch] 监听已启动");

    // 后台线程：收集事件并按文件去重后批量处理
    let bgd_cb = bgd_root.clone();
    let cfg_cb = cfg.clone();
    let log_cb = log.clone();
    std::thread::spawn(move || {
        // path -> (deleted, last_seen)
        let mut pending: HashMap<PathBuf, (bool, Instant)> = HashMap::new();
        loop {
            match rx.recv_timeout(Duration::from_millis(DEBOUNCE_MS)) {
                Ok(event) => {
                    for path in event.paths {
                        if path.is_dir() {
                            continue;
                        }
                        let deleted = matches!(event.kind, EventKind::Remove(_));
                        pending
                            .entry(path)
                            .and_modify(|e| {
                                e.0 = deleted;
                                e.1 = Instant::now();
                            })
                            .or_insert((deleted, Instant::now()));
                    }
                }
                Err(mpsc::RecvTimeoutError::Timeout) => {
                    // 处理已静默超过窗口的文件
                    let now = Instant::now();
                    let ready: Vec<PathBuf> = pending
                        .iter()
                        .filter(|(_, (_, t))| now.duration_since(*t) >= Duration::from_millis(DEBOUNCE_MS))
                        .map(|(p, _)| p.clone())
                        .collect();
                    if ready.is_empty() {
                        continue;
                    }
                    let log_line = |s: &str| (log_cb)(s);
                    for path in ready {
                        let (deleted, _) = pending.remove(&path).unwrap_or((false, now));
                        // 最终状态以文件实际存在性为准（避免误删）
                        let actually_deleted = deleted && !path.exists();
                        handle_file(&path, actually_deleted, &bgd_cb, &cfg_cb, &log_line);
                    }
                }
                Err(mpsc::RecvTimeoutError::Disconnected) => break,
            }
        }
    });

    Ok(watcher)
}
