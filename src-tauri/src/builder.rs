/// 把引号内的源码模块名前缀改写为运行时根名：'libs.xxx' -> 'bgd_libs_server.xxx' 等
pub fn rewrite_lua(content: &str, side: &str, cfg: &BgdConfig) -> String {
    let (libs_key, game_key) = if side == "server" {
        (&cfg.libs_server_target, &cfg.game_server_target)
    } else {
        (&cfg.libs_client_target, &cfg.game_client_target)
    };
    let libs_root = Path::new(libs_key)
        .file_name()
        .unwrap_or_default()
        .to_string_lossy()
        .into_owned();
    let game_root = Path::new(game_key)
        .file_name()
        .unwrap_or_default()
        .to_string_lossy()
        .into_owned();

    // 'libs.xxx' / 'libs' 两种形式都要改写（裸 require('libs') 加载运行时根）
    let re_libs = Regex::new(r#"(['"])libs(['".])"#).unwrap();
    let content = re_libs.replace_all(content, |caps: &Captures| {
        if &caps[2] == "." {
            format!("{}{}.", &caps[1], libs_root)
        } else {
            format!("{}{}{}", &caps[1], libs_root, &caps[2])
        }
    });
    let re_src = Regex::new(r#"(['"])src(['".])"#).unwrap();
    re_src
        .replace_all(&content, |caps: &Captures| {
            if &caps[2] == "." {
                format!("{}{}.", &caps[1], game_root)
            } else {
                format!("{}{}{}", &caps[1], game_root, &caps[2])
            }
        })
        .into_owned()
}

/// res 资源路径替换：把 'libs/res/<类型>/...' 或 'src/res/<类型>/...' 替换为运行时路径
/// 规则：sound 去掉 .ogg 扩展名，sprites 前缀 @<ProjectName>；各类型固定扩展名 + 资源存在性检查（黄色警告）
fn rewrite_res_paths(content: &str, bgd_root: &Path, _cfg: &BgdConfig, log: &LogFn) -> String {
    let project_name = read_project_name(bgd_root).unwrap_or_else(|_| "unknown".to_string());
    let project_root = bgd_root.parent().unwrap_or(bgd_root);
    let mut result = content.to_string();
    let mut warnings: Vec<String> = Vec::new();

    for code_set in ["libs", "src"] {
        for res_type in ["image", "particle", "sound", "spine", "sprites"] {
            let pattern = format!(r#"['"]({code_set}/res/{res_type}/[^'"]+)['"]"#);
            let re = Regex::new(&pattern).unwrap();
            result = re
                .replace_all(&result, |caps: &Captures| {
                    let full_path = &caps[1]; // libs/res/image/armor_dark.png
                    let rel_path = full_path
                        .trim_start_matches(&format!("{code_set}/res/{res_type}/"));
                    let (new_path, warn) = rewrite_single_res_path(
                        code_set, res_type, rel_path, &project_name, project_root,
                    );
                    if let Some(w) = warn {
                        warnings.push(w);
                    }
                    format!("'{new_path}'")
                })
                .into_owned();
        }
    }

    // 输出黄色警告（构建日志流）
    for w in warnings {
        log(&format!("[warn] {w}"));
    }

    result
}

/// 重写单个 res 路径，返回 (新路径, 可选警告)
fn rewrite_single_res_path(
    code_set: &str,
    res_type: &str,
    rel_path: &str,
    project_name: &str,
    project_root: &Path,
) -> (String, Option<String>) {
    let prefix = if code_set == "libs" { "bgd_libs_client" } else { "bgd_game_client" };
    let base = project_root.join(".bgd").join(code_set).join("res").join(res_type);

    match res_type {
        "image" => {
            let name = rel_path.trim_end_matches(".png");
            let file = base.join(format!("{name}.png"));
            let warn = if !file.exists() {
                Some(format!("资源不存在: {code_set}/res/image/{rel_path}（期望 .png）"))
            } else {
                None
            };
            (format!("image/image/{prefix}/{name}.png"), warn)
        }
        "particle" => {
            let name = rel_path.trim_end_matches(".effect");
            let file = base.join(format!("{name}.effect"));
            let warn = if !file.exists() {
                Some(format!("资源不存在: {code_set}/res/particle/{rel_path}（期望 .effect）"))
            } else {
                None
            };
            (format!("res/effect/{prefix}/{name}.effect"), warn)
        }
        "sound" => {
            let name = rel_path.trim_end_matches(".ogg");
            let file = base.join(format!("{name}.ogg"));
            let warn = if !file.exists() {
                Some(format!("资源不存在: {code_set}/res/sound/{rel_path}（期望 .ogg）"))
            } else {
                None
            };
            (format!("res/sound/{prefix}/{name}"), warn)
        }
        "spine" => {
            let name = rel_path.trim_end_matches(".skel");
            let file = base.join(format!("{name}.skel"));
            let warn = if !file.exists() {
                Some(format!("资源不存在: {code_set}/res/spine/{rel_path}（期望 .skel）"))
            } else {
                None
            };
            (format!("spine/{prefix}/{name}"), warn)
        }
        "sprites" => {
            // sprites：目录无扩展名，文件保留扩展名
            let path = base.join(rel_path);
            let (name, ext) = if path.is_dir() {
                (rel_path.to_string(), String::new())
            } else {
                match path.extension() {
                    Some(e) => (
                        rel_path.trim_end_matches(&format!(".{}", e.to_string_lossy())).to_string(),
                        format!(".{}", e.to_string_lossy()),
                    ),
                    None => (rel_path.to_string(), String::new()),
                }
            };
            let warn = if !path.exists() {
                Some(format!("资源不存在: {code_set}/res/sprites/{rel_path}"))
            } else {
                None
            };
            (format!("@{project_name}/image/sprites/{prefix}/{name}{ext}"), warn)
        }
        _ => (rel_path.to_string(), None),
    }
}

// ---------------------------------------------------------------- 文件复制

fn ext_of(path: &Path) -> String {
    path.extension()
        .unwrap_or_default()
        .to_string_lossy()
        .to_lowercase()
}

/// 单文件复制：lua 改写模块名；html/css/js 包装为 lua 字符串模块；其余二进制原样
fn transform_and_write(src: &Path, dest: &Path, side: &str, cfg: &BgdConfig, bgd_root: &Path, log: &LogFn) -> Result<bool> {
    let ext = ext_of(src);
    let dest = if TEXT_EXTS.contains(&ext.as_str()) && ext != "lua" {
        dest.with_extension("lua")
    } else {
        dest.to_path_buf()
    };

    if let Some(parent) = dest.parent() {
        fs::create_dir_all(parent)?;
    }

    if TEXT_EXTS.contains(&ext.as_str()) {
        let content = fs::read_to_string(src)
            .with_context(|| format!("无法读取源文件: {}", src.display()))?;
        let content = if ext == "lua" {
            let content = rewrite_lua(&content, side, cfg);
            rewrite_res_paths(&content, bgd_root, cfg, log)
        } else {
            format!("return [===[{content}]===]")
        };
        fs::write(&dest, content)?;
    } else {
        fs::copy(src, &dest)?;
    }
    Ok(true)
}

fn dest_for(rel: &str, side: &str, code_set: &str, bgd_root: &Path, cfg: &BgdConfig) -> PathBuf {
    let key = format!("{code_set}_{side}_target");
    let target = match key.as_str() {
        "libs_server_target" => &cfg.libs_server_target,
        "libs_client_target" => &cfg.libs_client_target,
        "game_server_target" => &cfg.game_server_target,
        _ => &cfg.game_client_target,
    };
    cfg.abs(bgd_root, target).join(rel.trim_start_matches('/'))
}

fn code_set_dir<'a>(code_set: &str, cfg: &'a BgdConfig) -> (&'a str, &'a [String]) {
    if code_set == "libs" {
        (&cfg.libs_dir, &cfg.libs_excludes)
    } else {
        (&cfg.game_dir, &cfg.game_excludes)
    }
}

fn sides_for(rel: &str) -> Vec<&'static str> {
    if rel.starts_with("/server/") {
        vec!["server"]
    } else if rel.starts_with("/client/") {
        vec!["client"]
    } else {
        vec!["server", "client"] // common 双端复制
    }
}

fn rel_of(src_abs: &Path, code_set: &str, bgd_root: &Path, cfg: &BgdConfig) -> Result<String> {
    let (dir, _) = code_set_dir(code_set, cfg);
    let src_root = cfg.abs(bgd_root, dir);
    Ok(format!(
        "/{}",
        src_abs
            .strip_prefix(&src_root)
            .with_context(|| format!("文件不在源目录内: {}", src_abs.display()))?
            .to_string_lossy()
            .replace('\\', "/")
    ))
}

/// 构建单个文件（白名单子目录内），返回产出数量
pub fn build_one_file(
    bgd_root: &Path,
    cfg: &BgdConfig,
    code_set: &str,
    src_abs: &Path,
    log: &LogFn,
) -> Result<usize> {
    let rel = rel_of(src_abs, code_set, bgd_root, cfg)?;
    if !in_whitelist(&rel) {
        return Ok(0);
    }
    let (_, excludes) = code_set_dir(code_set, cfg);
    if is_excluded(&rel, excludes) {
        log(&format!("[skip] excluded: [{code_set}] {rel}"));
        return Ok(0);
    }

    // res 资源目录：.lua 不同步（它是代码），其余资源文件同步到引擎目录
    if rel.starts_with("/res/") {
        if ext_of(src_abs) == "lua" {
            return Ok(0);
        }
        return sync_res_file(bgd_root, cfg, code_set, &rel, src_abs, log);
    }

    let mut count = 0;
    for side in sides_for(&rel) {
        let dest = dest_for(&rel, side, code_set, bgd_root, cfg);
        if transform_and_write(src_abs, &dest, side, cfg, bgd_root, log)? {
            log(&format!("[ok] {side}: [{code_set}] {rel}"));
            count += 1;
        }
    }
    Ok(count)
}

// ---------------------------------------------------------------- res 资源同步

/// res 资源类型 -> 引擎目标子路径（相对项目根）
/// image/particle/sound/spine/sprites 五类，前缀按 code_set 区分
fn res_target_subdir(res_type: &str, code_set: &str) -> Option<String> {
    let prefix = if code_set == "libs" { "bgd_libs_client" } else { "bgd_game_client" };
    match res_type {
        "image" => Some(format!("ui/image/image/{prefix}")),
        "particle" => Some(format!("res/effect/{prefix}")),
        "sound" => Some(format!("res/sound/{prefix}")),
        "spine" => Some(format!("ui/spine/{prefix}")),
        "sprites" => Some(format!("ui/image/sprites/{prefix}")),
        _ => None,
    }
}

/// 同步单个 res 资源文件到引擎目录（二进制原样复制）
fn sync_res_file(
    bgd_root: &Path,
    cfg: &BgdConfig,
    code_set: &str,
    rel: &str,
    src_abs: &Path,
    log: &LogFn,
) -> Result<usize> {
    let (_, excludes) = code_set_dir(code_set, cfg);
    if is_excluded(rel, excludes) {
        log(&format!("[skip] res excluded: [{code_set}] {rel}"));
        return Ok(0);
    }
    // rel 形如 /res/<type>/<path...>
    let parts: Vec<&str> = rel.trim_start_matches('/').splitn(3, '/').collect();
    if parts.len() < 3 {
        return Ok(0);
    }
    let res_type = parts[1];
    let sub_path = parts[2];
    let Some(target_sub) = res_target_subdir(res_type, code_set) else {
        log(&format!("[warn] 未知资源类型: [{code_set}] {rel}"));
        return Ok(0);
    };
    let project_root = bgd_root.parent().unwrap_or(bgd_root);
    let dest = project_root.join(&target_sub).join(sub_path);
    if let Some(parent) = dest.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::copy(src_abs, &dest)?;
    log(&format!("[ok] res: [{code_set}] {rel} -> {target_sub}/{sub_path}"));
    Ok(1)
}

