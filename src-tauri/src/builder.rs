/// 原文保留 + 标记 + 框架 entrance + 游戏 entrance。幂等。
pub fn update_entrance(kind: &str, bgd_root: &Path, cfg: &BgdConfig, log: &LogFn) -> Result<()> {
    let filename = format!("{kind}.lua");
    let libs_entrance = cfg.abs(bgd_root, &cfg.libs_dir).join("entrance").join(&filename);
    let game_entrance = cfg.abs(bgd_root, &cfg.game_dir).join("entrance").join(&filename);
    let dest_rel = if kind == "server" {
        &cfg.server_entrance
    } else {
        &cfg.client_entrance
    };
    let dest = cfg.abs(bgd_root, dest_rel);

    // entrance 内容同样要走模块名改写（引号内 libs./src. 前缀 -> 运行时根名）
    let libs_content = rewrite_lua(&fs::read_to_string(&libs_entrance).unwrap_or_default(), kind, cfg);
    let game_content = rewrite_lua(&fs::read_to_string(&game_entrance).unwrap_or_default(), kind, cfg);

    // 提取原文：含标记取标记之前；不含标记则整个现有文件视为原文（首次接入）。
    // 防御：若"原文"自身仍含标记（历史脏数据导致标记堆积），视为损坏，丢弃原文，
    // 让本次构建以空原文重新生成（一次构建即自愈）。
    let mut original = String::new();
    if dest.exists() {
        let existing = fs::read_to_string(&dest).unwrap_or_default();
        let mut candidate = match existing.find(ENTRANCE_MARKER) {
            Some(pos) => existing[..pos].to_string(),
            None => existing,
        };
        if candidate.contains(ENTRANCE_MARKER) {
            log(&format!(
                "[warn] 入口文件检测到残留标记（历史脏数据），已丢弃损坏原文并重建: {}",
                dest.display()
            ));
            candidate = String::new();
        }
        original = candidate;
    }

    let mut generated = libs_content.clone();
    if !game_content.is_empty() {
        if !libs_content.is_empty() {
            generated.push_str("\n\n-- ===== 游戏入口代码 =====\n\n");
        }
        generated.push_str(&game_content);
    }

    let mut parts: Vec<String> = Vec::new();
    if !original.trim().is_empty() {
        parts.push(original.trim_end_matches('\n').to_string());
    }
    parts.push(ENTRANCE_MARKER.to_string());
    if !generated.trim().is_empty() {
        parts.push(generated.trim_end_matches('\n').to_string());
    }
    let merged = format!("{}\n", parts.join("\n\n"));

    if let Some(parent) = dest.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(&dest, merged)?;
    log(&format!("[ok] entrance: {kind} -> {}", dest.display()));
    Ok(())
}

/// clean 时还原入口：删除标记及之后内容，恢复原文；无标记则不碰
fn restore_entrance(kind: &str, bgd_root: &Path, cfg: &BgdConfig, log: &LogFn) -> Result<()> {
    let dest_rel = if kind == "server" {
        &cfg.server_entrance
    } else {
        &cfg.client_entrance
    };
    let dest = cfg.abs(bgd_root, dest_rel);
    if !dest.exists() {
        return Ok(());
    }
    let existing = fs::read_to_string(&dest).unwrap_or_default();
    if let Some(pos) = existing.find(ENTRANCE_MARKER) {
        fs::write(&dest, &existing[..pos])?;
        log(&format!("  -> 入口已还原: {}", dest.display()));
    }
    Ok(())
}

