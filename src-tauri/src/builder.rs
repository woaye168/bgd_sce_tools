/// code set 根的 init.lua 作为模板渲染到产物根（{{target}}/{{module}}/{{time}}）
pub fn render_root_init(bgd_root: &Path, cfg: &BgdConfig, log: &LogFn) -> Result<()> {
    for code_set in ["libs", "game"] {
        let (dir, _) = code_set_dir(code_set, cfg);
        let tpl = cfg.abs(bgd_root, dir).join("init.lua");
        if !tpl.exists() {
            log(&format!("[warn] 根 init.lua 不存在: {}", tpl.display()));
            continue;
        }
        let content = fs::read_to_string(&tpl)?;
        for side in ["server", "client"] {
            let key = format!("{code_set}_{side}_target");
            let target_rel = match key.as_str() {
                "libs_server_target" => &cfg.libs_server_target,
                "libs_client_target" => &cfg.libs_client_target,
                "game_server_target" => &cfg.game_server_target,
                _ => &cfg.game_client_target,
            };
            let target = cfg.abs(bgd_root, target_rel);
            let target_name = target
                .file_name()
                .unwrap_or_default()
                .to_string_lossy()
                .into_owned();
            let time_str = std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .map(|d| d.as_secs().to_string())
                .unwrap_or_default();
            let out = content
                .replace("{{target}}", &target_name)
                .replace("{{module}}", side)
                .replace("{{time}}", &time_str);
            fs::create_dir_all(&target)?;
            fs::write(target.join("init.lua"), out)?;
            log(&format!("[ok] {side}: init.lua <- {code_set}/init.lua"));
        }
    }
    Ok(())
}

